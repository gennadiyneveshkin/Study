import re

# Нужно получить текст без <p></p>
s = """
<p>Какой-то текст</p>
<p>Какой-то текст</p>
<p>Какой-то текст</p>
<p>Какой-то текст</p>
<p>Какой-то текст</p>
"""

# Ищет все совпадения
res = re.findall('<p>(.*?)</p>', s)
print(res)

# Ищет только первое совпадение
res2 = re.search('<p>(.*?)</p>', s)
print(res2)

res3 = re.search('<p>(.*?)</p>', s).group(0)
print(res3)

# Замена по регулярному выражению
res4 = re.sub('<p>(.*?)</p>', 'Заменили текст на этот', s)
print(res4)

res6 = re.sub(r'<p>(.*?)</p>', r'Заменили текст на этот и оставили то, что было: \g<1>', s)
print(res6)

# Получить текст без цифр
s2 = 'Меня зовут Андрон 23 и опять какой то текст 128 и опять текст'
res5 = re.split(r'\d+', s2)
print(res5)

# Компиляция регулярного вырожения - созание регулярного выраженя зарание и потом его можно исопльзовать
# DOTALL и MULTILINE - это флаги
# DOTALL означает что точка значит любой символ, в том числе переход на новую строку
# | означает что добавляем еще один флаг
# MULTILINE означает что символы ^ означает начало и $ конец строки
comp = re.compile('<p>(.*?)</p>', re.DOTALL | re.MULTILINE)

s3 = """
first line

second line

third line
"""

# Компилируем регулярное вырожение regular
regular = re.compile('^[A-z ]+$', re.MULTILINE)

# Вызываем регулярное выражение для функции findall
res7 = regular.findall(s3)

print(res7)