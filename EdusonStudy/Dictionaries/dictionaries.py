# пополнение словаря элементами другого словаря (объединение словарей)
# если ключи совпадут, по перезапишется значение из нового словаря
s = {1: 'a', 2: 'b', 3: 'c'}
s1 = {4: 'd', 1 : 'e'}
s.update(s1)
print(s)

# альтернативный способ объединения словарей
s | s1
print(s)

# удаление значения из словаря по ключу
s.pop(1)
print(s)

s[5] = 1000
print(s)
s.popitem() # удаление последнего добавленного значения из словаря
print(s)

# альтеранативный способ удаления значения из словаря по ключу
del s[2]
print(s)

