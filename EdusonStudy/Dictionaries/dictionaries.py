# Словари

d = {} # пустое множество имеет класс dict "словарь"
print(type(d))

# словарь содержит пары "ключ - значение"
d = {
    'a' : 1,
    'b' : [1, 2, 3],
    'c' : 'abcde'
}
print(d)

# создание словаря с помощью функции dict
d = dict ([(1, 'a'), (2, 'b'), (3, 'c')])
print(d)

# добавление нового элемента 123 с ключом 'a' в словарь
d['a'] = 123
print(d)

# перезапись значения по тому же ключу
d['a'] = 321
print(d)

# кортеж в качестве ключа
a = (1, 2, 3)
d[a] = 'my tuple'
print(d)

# получение значения из словаря по ключу 'a'
# если такого ключа нет, выдаст ошибку
x = d['a']
print(x)

