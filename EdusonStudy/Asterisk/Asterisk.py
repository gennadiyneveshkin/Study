# Прием произвольного числа аргументов функции
def foo(*args, **kwargs):

    # Все позиционные аргументы, принятые функцией будут  укомплектованы в виде TODO строк в кортеж
    # Все именованные аргументы будут укомплектованы в виде TODO пар ключ-значение в словарь
    print(args, kwargs)

    # Вывод позиционных аргументов
    for i, arg in enumerate(args):
        print(f'Аргумент {i}: {arg}')

    # Вывод ключей именованных аргументов
    for i, kwarg in enumerate(kwargs, len(args)):
        print(f'Аргумент {i}: {kwarg}')

    # Вывоз ключей и значений именнованных аргументов
    # метод items() формирует список кортежей, в каждом кортеже пары ключ-значекние словаря kwargs
    for k, v in kwargs.items():
        print(f'{k}: {v}')


