# Распаковка объектов

lst = [1, 2, 3, 4, 5]

# Например, нас интересует именно первый элемент списка lst
# Нам нужно сохранить его в отдельную переменную a, а все остальные в переменную b
# Это можно сделать так:

a = lst[0]
b = lst[1:]
print(a)
print(b)

# Но это же можно сделать и так:
# Здесь питон переменной a присвоит первый элемент списка lst, а переменной b все остальное
a, *b = lst

print(a)
print(b)

# переменная со звездочкой, в нашем случае b TODO всегда будет списком
# даже если идет распаковка длугой коллекции, например, кортежа

a, *b = (1, 2, 3)
print(a)
print(b)

# Распаковка и объединение разных коллекций
a = [1, 2, 3]
b = (4, 5, 6)
c = {7, 8, 9}
d = {'a':1, 'b':2, 'c':3}

# Получим список из элементов всех коллекций
res_list = [*a, *b, *c, *d]

# Получим кортеж из элементов всех коллекций
res_tuple = (*a, *b, *c, *d)

print(res_list)
print(res_tuple)