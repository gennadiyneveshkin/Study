# ИТЕРАТОР
# Цель - пройтись по элементам, вернуть следующий или выдать ошибку
# Если есть элемент внутри итерируемого объекта - возвращаем его
# Если нет или не осталось - выдаем исключение StopIteration
# Выдача следующего элемента осуществляется с помощью метода __next__

# ИТЕРИРУЕМЫЙ ОБЪЕКТ
# Цель - создать итератор
# Реилизованы методы __iter__ или __getitem__

lst = [1, 2, 3]
it = iter(lst)         # c помощью функции iter() которая с помощью метода __iter__ создает итератор
list(it)          # [1, 2, 3], итератор it теперь исчерпан

for x in lst:     # тут создаётся НОВЫЙ итератор, всё ок
    print(x)      # 1 2 3

# Этот код напичатает 3, 4, 5 и выведет ошибку Stop Ireration когда элементы закончатся
lst = [3, 4, 5]
it = iter(lst)
while True:
    print(next(it))

# Когда мы пишем for el in lst Python берет объект - список lst
# и с помощью функции iter() вызывает метор __iter__
# и преобразовывает объект lst к итератору it = iter(lst)
# и дальше с помощью функции next() перебираются элементы
# и выводятся на печать
# Но в цикле for мы не получим ошибку StopIteration а плавно выйдем из цикла
