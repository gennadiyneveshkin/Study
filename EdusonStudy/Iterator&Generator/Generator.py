# Обычная функция возведения числа в квадрат
def square(x):
    x = x**2
    return x
print(square(3))

# Возводит число x в квадрат, но при каждом вызове функция делает это TODO только один раз
# Значение x после возведения увеличивается на 1 (можно прописать другое условие)
# Функция становится !!! на паузу !!! , до тех пор пока ее не вызовут еще раз
# Можно вызывать сколько угодно раз
# Вызываем с помощью функции next()
def square2(x):
    while True:
        yield x**2
        x += 1

s = square2(5)
print(s)

print (next(s))
print (next(s))
print (next(s))

# Генератор чисел Фибоначчи
def fib():

    # стартовые значения последовательности Фибоначчи
    a, b = 0, 1

    # бесконечный цикл: генератор может выдавать числа сколько угодно, пока его спрашивают
    while True:

        # yield a - ключевое слово, которое делает функцию генератором.
        # Когда код доходит до yield, он:
        # «отдаёт» текущее значение a наружу,
        # замораживает состояние функции (все локальные переменные и текущую строку),
        # и ждёт следующего запроса
        yield a

        # с этой строки продолжится выполнение кода при следующем запросе результата от генератора
        # классическое обновление пары чисел Фибоначчи через распаковку кортежа
        a, b = b, a + b

# Здесь f - это объект-генератор, а не список и не результат вычислений.
# Он ещё ничего не посчитал: вычисления начнутся только когда мы попросим следующее значение.
f = fib()

for _ in range (8):

    # next(f) запрашивает у генератора следующее значение
    # генератор «просыпается» там, где остановился,
    # выполняет код до следующего yield,
    # отдаёт значение,
    # снова «засыпает».
    # Что будет выведено: 0, 1, 1, 2, 3, 5, 8, 13 первые 8 чисел Фибоначчи.
    print(next(f))

# Поскольку генератор «помнит» своё состояние,
# он продолжает с того места, где остановился после первого цикла.
# То есть следующие числа будут идти сразу после 13: 21, 34, 55, 89, 144.
# Как только встретится 144 (оно больше 100), цикл прервётся.
# Итого второй цикл выведет: 21, 34, 55, 89, 144, а затем остановится.

# Здесь цик for запрашивает следующий элемент у генератора f, который также является итерируемым объектом
# Разница например, со списком - он уже всё содержит, а генератор каждый раз делает шаг и выдаёт значение.
for el in f:

    print(el)
    if el > 100:
        break


