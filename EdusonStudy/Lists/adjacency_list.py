# adj - это общепринятое в алгоритмах и работе с графами сокращение от английского adjacency («смежность»).
# Создаем список из списков, изначально пустых (adjacency list)
# _ здесь просто имя переменной-заполнителя. Оно означает:
# «мне не важно значение этой переменной, я просто хочу повторить действие нужное число раз».
# Можно было бы написать for i in range(5), но принято ставить _, потому что данная переменная нигде больше
# использоавться не будет

adj = [[] for _ in range(5)]
print(adj)